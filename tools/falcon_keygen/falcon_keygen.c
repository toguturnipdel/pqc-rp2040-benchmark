/*
 * Off-device Falcon key provisioning for the RP2040 benchmark (Reviewer 4,
 * point 2). Generates one Falcon-512 and one Falcon-1024 key pair on the host
 * with the same wolfSSL commit as the firmware, checks export/import and
 * sign/verify round trips, and writes firmware/src/falcon_ext_keys.h.
 *
 * Build and run (from the repository root):
 *   make -C tools/falcon_keygen WOLFSSL_ROOT=~/pico/wolfssl
 *   ./tools/falcon_keygen/falcon_keygen firmware/src/falcon_ext_keys.h
 */
#include <stdio.h>
#include <string.h>
#include <time.h>
#include <wolfssl/wolfcrypt/settings.h>
#include <wolfssl/version.h>
#include <wolfssl/wolfcrypt/random.h>
#include <wolfssl/wolfcrypt/falcon.h>

int host_rng_seed(unsigned char *out, unsigned int sz)
{
    FILE *u = fopen("/dev/urandom", "rb");
    size_t n = u ? fread(out, 1, sz, u) : 0;
    if (u) fclose(u);
    return (n == sz) ? 0 : -1;
}

static byte priv[FALCON_MAX_PRV_KEY_SIZE], pub[FALCON_MAX_PUB_KEY_SIZE], sig[FALCON_MAX_SIG_SIZE];

static void emit(FILE *f, const char *name, const byte *b, word32 n)
{
    fprintf(f, "static const unsigned char %s[%u] = {", name, (unsigned)n);
    for (word32 i = 0; i < n; i++) fprintf(f, "%s0x%02x,", (i % 16) ? " " : "\n    ", b[i]);
    fprintf(f, "\n};\n");
}

static int one(FILE *f, WC_RNG *rng, byte level, const char *tag)
{
    falcon_key k, k2;
    word32 privSz = sizeof priv, pubSz = sizeof pub, sl = sizeof sig;
    const byte msg[32] = { 1, 2, 3 };
    int ret, res = 0;
    clock_t c0;

    wc_falcon_init(&k);
    if ((ret = wc_falcon_set_level(&k, level)) != 0) return ret;
    c0 = clock();
    if ((ret = wc_falcon_make_key(&k, rng)) != 0) { fprintf(stderr, "%s keygen %d\n", tag, ret); return ret; }
    fprintf(stderr, "%s: host keygen %.2f s\n", tag, (double)(clock() - c0) / CLOCKS_PER_SEC);
    if ((ret = wc_falcon_export_key(&k, priv, &privSz, pub, &pubSz)) != 0) { fprintf(stderr, "export %d\n", ret); return ret; }

    /* Round trip: import into a fresh key, sign with it, verify with the original */
    wc_falcon_init(&k2);
    wc_falcon_set_level(&k2, level);
    if ((ret = wc_falcon_import_private_key(priv, privSz, pub, pubSz, &k2)) != 0) { fprintf(stderr, "import %d\n", ret); return ret; }
    if ((ret = wc_falcon_sign_msg(msg, sizeof msg, sig, &sl, &k2, rng)) != 0) { fprintf(stderr, "sign %d\n", ret); return ret; }
    if ((ret = wc_falcon_verify_msg(sig, sl, msg, sizeof msg, &res, &k)) != 0 || res != 1) {
        fprintf(stderr, "verify ret=%d res=%d\n", ret, res); return ret ? ret : -1;
    }
    fprintf(stderr, "%s: priv %u B, pub %u B, sig %u B, round trip ok\n", tag, privSz, pubSz, sl);

    char nm[64];
    snprintf(nm, sizeof nm, "%s_PRIV", tag); emit(f, nm, priv, privSz);
    snprintf(nm, sizeof nm, "%s_PUB", tag);  emit(f, nm, pub, pubSz);
    wc_falcon_free(&k); wc_falcon_free(&k2);
    return 0;
}

int main(int argc, char **argv)
{
    WC_RNG rng;
    FILE *f = (argc > 1) ? fopen(argv[1], "w") : stdout;
    if (!f) { perror("open"); return 1; }
    if (wolfCrypt_Init() || wc_InitRng(&rng)) { fprintf(stderr, "init failed\n"); return 1; }
    fprintf(f, "/* Generated by tools/falcon_keygen with wolfSSL %s (host). Do not edit.\n"
               " * Falcon key pairs provisioned off-device (Reviewer 4, point 2). */\n"
               "#ifndef FALCON_EXT_KEYS_H\n#define FALCON_EXT_KEYS_H\n", LIBWOLFSSL_VERSION_STRING);
    if (one(f, &rng, FALCON_LEVEL1, "FALCON512") || one(f, &rng, FALCON_LEVEL5, "FALCON1024")) return 1;
    fprintf(f, "#endif\n");
    if (f != stdout) fclose(f);
    wc_FreeRng(&rng);
    return 0;
}
